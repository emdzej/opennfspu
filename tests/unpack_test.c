static int fails;

static void check(const char *what, const uint8_t *src)
{
    static const char text[] = "Porsche Unleashed!!!!!!!! 911 911 911 \0\0\0\0\0\0 the end";
    uint32_t n = UNPACK_size(src);
    uint8_t *out = calloc(1, n + 1);
    uint32_t r = UNPACK_dispatch(src, out);
    bool ok = n == sizeof text - 1 && r == n && !memcmp(out, text, n);
    printf("%s: %s\n", what, ok ? "ok" : "bad");
    if (!ok) fails++;
    free(out);
}

int main(void)
{
    check("huff 0x30", huff30);
    check("huff 0x32 (summed once)", huff32);
    check("huff 0x34 (summed twice)", huff34);
    printf(fails ? "unpack_test: %d failures\n" : "unpack_test: ok\n", fails);
    return fails ? 1 : 0;
}
